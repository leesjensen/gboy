#!/usr/bin/env python3
"""Turn data/recipes.json into a seed.sql of batched, idempotent upserts.

usage: seed_recipes.py RECIPES_JSON OUT_SQL keep|overwrite
"""
import json
import sys
from pathlib import Path

BATCH_SIZE = 100
CATEGORY_ORDER = [
    "appetizers", "backpacking", "belgian", "breads", "breakfast", "desserts",
    "drinks", "entrees", "salads", "sauces", "sides", "soups",
]


def dollar_quote(text):
    n = 0
    while f"$seed{n}$" in text:
        n += 1
    return f"$seed{n}${text}$seed{n}$"


def main():
    source, out_file, mode = Path(sys.argv[1]), Path(sys.argv[2]), sys.argv[3]
    recipes = json.loads(source.read_text(encoding="utf-8"))

    categories = {}
    for recipe in recipes:
        categories.setdefault(recipe["category"], recipe.get("categoryName") or recipe["category"])
    rank = {cid: i for i, cid in enumerate(CATEGORY_ORDER)}
    category_rows = [
        {"id": cid, "name": name, "sort_order": rank.get(cid, len(rank))}
        for cid, name in sorted(categories.items(), key=lambda kv: (rank.get(kv[0], len(rank)), kv[0]))
    ]
    parts = [f"""-- Generated by install/supabase/seed_recipes.py from {source.name} ({mode}). Do not edit.
""", f"""
insert into public.categories (id, name, sort_order)
select id, name, sort_order
from jsonb_to_recordset({dollar_quote(json.dumps(category_rows, ensure_ascii=False))}::jsonb)
  as c(id text, name text, sort_order integer)
on conflict (id) do update set name = excluded.name, sort_order = excluded.sort_order;
"""]

    conflict = (
        """do update set
  title = excluded.title,
  category_id = excluded.category_id,
  subcategory = excluded.subcategory,
  source_page = excluded.source_page,
  source_end_page = excluded.source_end_page,
  blocks = excluded.blocks,
  source_text = excluded.source_text"""
        if mode == "overwrite" else "do nothing"
    )

    for start in range(0, len(recipes), BATCH_SIZE):
        rows = [
            {
                "id": r["id"],
                "title": r["title"],
                "category_id": r["category"],
                "subcategory": r.get("subcategory") or "",
                "source_page": r.get("sourcePage"),
                "source_end_page": r.get("sourceEndPage"),
                "blocks": r.get("blocks") or [],
                "source_text": r.get("sourceText") or "",
            }
            for r in recipes[start:start + BATCH_SIZE]
        ]
        sql = f"""
insert into public.recipes
  (id, title, category_id, subcategory, source_page, source_end_page, blocks, source_text)
select id, title, category_id, subcategory, source_page, source_end_page, blocks, source_text
from jsonb_to_recordset({dollar_quote(json.dumps(rows, ensure_ascii=False))}::jsonb)
  as r(id text, title text, category_id text, subcategory text,
       source_page integer, source_end_page integer, blocks jsonb, source_text text)
on conflict (id) {conflict};
"""
        parts.append(sql)

    out_file.write_text("".join(parts), encoding="utf-8")

    print(f"Prepared {len(category_rows)} categories and {len(recipes)} recipes ({mode})")


if __name__ == "__main__":
    main()
